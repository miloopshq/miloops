// A private npm registry on this machine (Verdaccio), for trying MILOOPS exactly as a user would install it,
// without publishing anything to npmjs.com. Only `miloops` lives here; every other package is proxied from
// npmjs.com, so installs behave normally. See docs/end-user-test.md → "Private trial".
//
//   npm run registry:local              start the registry (http://127.0.0.1:4873), leave it running
//   npm run registry:local -- publish   build and publish the current miloops to it (as <version>-local.<time>)
//   npm run registry:local -- status    what is published there
import { execFileSync, spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const home = path.join(os.homedir(), '.miloops-registry');
const url = 'http://127.0.0.1:4873';
const [cmd = 'start'] = process.argv.slice(2);

// npm needs a token to publish: a local user on this registry, kept in a file that only commands here use.
const npmrc = path.join(home, '.npmrc');
async function ensureToken() {
  if (fs.existsSync(npmrc)) return;
  const user = { name: 'local', password: 'local-registry', email: 'local@localhost', type: 'user' };
  const r = await fetch(`${url}/-/user/org.couchdb.user:local`, {
    method: 'PUT',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ _id: 'org.couchdb.user:local', ...user, roles: [], date: new Date().toISOString() }),
  });
  const { token } = await r.json();
  if (!token) throw new Error(`could not log in to ${url} (${r.status}); is the registry running?`);
  fs.writeFileSync(npmrc, `//127.0.0.1:4873/:_authToken=${token}\n`);
}
const npm = (args, opts = {}) =>
  execFileSync('npm', [...args, '--registry', url, '--userconfig', npmrc], { cwd: repo, stdio: 'inherit', ...opts });

if (cmd === 'start') {
  fs.mkdirSync(path.join(home, 'storage'), { recursive: true });
  fs.writeFileSync(
    path.join(home, 'config.yaml'),
    `# Generated by scripts/registry-local.mjs
storage: ./storage
listen: 127.0.0.1:4873
auth:
  htpasswd:
    file: ./htpasswd
    max_users: 10
uplinks:
  npmjs:
    url: https://registry.npmjs.org/
packages:
  # Only the local build: no proxy, so the npm placeholder never mixes in.
  miloops:
    access: $all
    publish: $all
    unpublish: $all
  '**':
    access: $all
    publish: $authenticated
    proxy: npmjs
log: { type: stdout, format: pretty, level: warn }
`,
  );
  fs.rmSync(npmrc, { force: true });
  console.log(`Private registry: ${url}  (storage: ${home}/storage)`);
  console.log('Next: npm run registry:local -- publish   (in another terminal)');
  const p = spawn('npx', ['-y', 'verdaccio@7', '--config', path.join(home, 'config.yaml')], { stdio: 'inherit' });
  p.on('exit', (code) => process.exit(code ?? 0));
} else if (cmd === 'publish') {
  await ensureToken();
  // A unique prerelease per publish, so npx always resolves the build you just made.
  const base = JSON.parse(fs.readFileSync(path.join(repo, 'packages/cli/package.json'), 'utf8')).version;
  const version = `${base}-local.${new Date().toISOString().replace(/\D/g, '').slice(0, 14)}`;
  const pkgFile = path.join(repo, 'packages/cli/package.json');
  const original = fs.readFileSync(pkgFile, 'utf8');
  try {
    fs.writeFileSync(pkgFile, original.replace(`"version": "${base}"`, `"version": "${version}"`));
    npm(['publish', '-w', 'miloops', '--tag', 'latest']);
  } finally {
    fs.writeFileSync(pkgFile, original);
  }
  console.log(`\nPublished miloops@${version} to ${url}.`);
  console.log(`Use it like a user would:  npm config set registry ${url}   then  npx miloops`);
  console.log('Back to npmjs.com:         npm config delete registry');
} else if (cmd === 'status') {
  await ensureToken();
  npm(['view', 'miloops', 'versions', 'dist-tags']);
} else {
  console.error(`unknown command: ${cmd} (start | publish | status)`);
  process.exit(1);
}
