// Bakes the approved v4 CRT head into src/milo/art.ts: a 32×32 base frame plus independent eye / mouth / light
// patches, and the hand-simplified 16×16 head for xs. Verifies that base + patches reproduce every v4 state.
// Usage: node tools/bake-art.mjs [out=src/milo/art.ts]
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { CONCEPTS, PAL, draw, drawMini } from './robot-concepts-v4.mjs';

const OUT = resolve(process.argv[2] || 'src/milo/art.ts');
const c = CONCEPTS.crt;
const toRows = (g) => g.p.map((r) => r.map((t) => t ?? '.'));

const frames = Object.fromEntries(
  ['idle', 'blink', 'speaking', 'speakB', 'thinking', 'alert'].map((s) => [s, toRows(draw(c, s))]),
);
const mini = toRows(drawMini('crt'));

const diff = (a, b) => {
  const cells = [];
  a.forEach((row, y) =>
    row.forEach((t, x) => {
      if (b[y][x] !== t) cells.push([y, x, b[y][x]]);
    }),
  );
  return cells;
};
const base = frames.idle;
const rowsOf = (cells) => [...new Set(cells.map(([y]) => y))];
const mouthRows = new Set(rowsOf(diff(base, frames.speaking)));
const eyeTop = Math.min(...rowsOf(diff(base, frames.blink))) - 2;
const mouthBottom = Math.max(...mouthRows) + 1;
const region = (y) => (mouthRows.has(y) ? 'mouth' : y < eyeTop || y > mouthBottom ? 'light' : 'eyes');
const pick = (state, want) => diff(base, frames[state]).filter(([y]) => region(y) === want);

const patches = {
  eyes: { closed: pick('blink', 'eyes'), aside: pick('thinking', 'eyes'), wide: pick('alert', 'eyes') },
  mouths: { open: pick('speaking', 'mouth'), mid: pick('speakB', 'mouth'), aside: pick('thinking', 'mouth') },
  lights: { dim: pick('thinking', 'light'), alert: pick('alert', 'light') },
};
const miniAlert = [];
mini.forEach((row, y) =>
  row.forEach((t, x) => {
    if (t[0] === 'O') miniAlert.push([y, x, 'R' + t.slice(1)]);
  }),
);

// One character per token.
const tokens = new Set(['R1']);
for (const rows of [...Object.values(frames), mini])
  for (const r of rows) for (const t of r) if (t !== '.') tokens.add(t);
const POOL = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789';
const sorted = [...tokens].sort();
const key = Object.fromEntries(sorted.map((t, i) => [t, POOL[i]]));
key['.'] = '.';
const enc = (rows) => rows.map((r) => r.map((t) => key[t]).join(''));
const encPatch = (cells) => {
  const runs = [];
  for (const [y, x, t] of cells.sort((a, b) => a[0] - b[0] || a[1] - b[1])) {
    const last = runs[runs.length - 1];
    if (last && last[0] === y && last[1] + last[2].length === x) last[2] += key[t];
    else runs.push([y, x, key[t]]);
  }
  return runs;
};

// Verify: base + patches === every state.
const apply = (rows, ...ps) => {
  const g = rows.map((r) => [...r]);
  for (const p of ps)
    for (const [y, x, s] of p)
      [...s].forEach((ch, i) => {
        g[y][x + i] = ch;
      });
  return g.map((r) => r.join(''));
};
const P = (o) => Object.fromEntries(Object.entries(o).map(([k, v]) => [k, encPatch(v)]));
const enc_ = { eyes: P(patches.eyes), mouths: P(patches.mouths), lights: P(patches.lights) };
const b = enc(base).map((r) => [...r]);
const checks = {
  blink: [enc_.eyes.closed],
  speaking: [enc_.mouths.open],
  speakB: [enc_.mouths.mid],
  thinking: [enc_.eyes.aside, enc_.mouths.aside, enc_.lights.dim],
  alert: [enc_.eyes.wide, enc_.lights.alert],
};
for (const [s, ps] of Object.entries(checks)) {
  if (apply(b, ...ps).join('\n') !== enc(frames[s]).join('\n')) throw new Error(`patch mismatch for ${s}`);
}

const json = (v) => JSON.stringify(v);
const lines = (rows) => `[\n${rows.map((r) => `  '${r}',`).join('\n')}\n]`;
const patchTs = (o) =>
  `{\n${Object.entries(o)
    .map(([k, v]) => `    ${k}: ${json(v)},`)
    .join('\n')}\n  }`;
const src = `// Generated by tools/bake-art.mjs from the approved v4 CRT head (tools/robot-concepts-v4.mjs). Do not edit by hand.
/* eslint-disable */
import type { Patch } from './types';

/** Palette key -> colour. Keys map to material tones (see TONES). R* tones appear only in alert patches. */
export const PALETTE: Record<string, string> = ${json(Object.fromEntries(sorted.map((t) => [key[t], PAL[t]])))};

/** Palette key -> material tone name (K outline, l* line, L shell, P headphones, C cushion, D glass, G glow, O status, R alert). */
export const TONES: Record<string, string> = ${json(Object.fromEntries(sorted.map((t) => [key[t], t])))};

/** 32×32 head, idle: steady eyes, flat mouth, status light on. */
export const HEAD: string[] = ${lines(enc(base))};

export const HEAD_PATCHES = {
  eyes: ${patchTs(enc_.eyes)},
  mouths: ${patchTs(enc_.mouths)},
  lights: ${patchTs(enc_.lights)},
} satisfies Record<string, Record<string, Patch>>;

/** Hand-simplified 16×16 head for xs and favicons. Never animates. */
export const MINI: string[] = ${lines(enc(mini))};

export const MINI_ALERT: Patch = ${json(encPatch(miniAlert))};
`;
writeFileSync(OUT, src);
console.log('wrote', OUT, `(${sorted.length} tones, verified ${Object.keys(checks).length} states)`);
